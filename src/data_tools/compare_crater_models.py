"""Compare the craters generated by the current code with those of a previous git revision.

The previous revision is extracted with ``git archive`` into a temporary folder and run in a separate process, so
both versions of ``lunasynth`` can be imported. Each version adds craters to the same piece of a base DEM with the
crater settings of its own ``ortho_nominal`` configuration. The script writes four figures:

- ``compare_tile.png``: the base DEM and the same tile with the craters of each version.
- ``compare_single.png``: the profile and hillshade of a single fresh 20 m crater.
- ``compare_gallery.png``: the four morphologies of the current model, fresh and degrading.
- ``compare_stats.png``: size-frequency distributions, morphologies and depth / diameter against age.

Example (compare with the revision before the crater model of ``lunasynth.craters``):
    uv run python src/data_tools/compare_crater_models.py --previous b917e01 --output-dir docs/images/craters
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_BASE_DEM = REPO_ROOT / "assets/base_meshes/NPB_final_adj_5mpp_surf_piece_1km_2_12.tif"
PIXEL_SIZE = 0.5  # m, resolution of the terrain the craters are added to
TILE_PIXELS = 80  # base DEM pixels of the compared tile


def generate(version: str, base_dem: str, output_dir: str, seed: int) -> None:
    """Generate craters with the ``lunasynth`` package on ``sys.path`` (run in its own process)."""
    import rasterio
    from lunasynth.terrain_enhancement import Crater, CraterField
    from scipy.ndimage import zoom

    out = Path(output_dir)
    with rasterio.open(base_dem) as src:
        base = src.read(1).astype(float)
        base_pixel_size = src.res[0]
    dem0 = zoom(base[:TILE_PIXELS, :TILE_PIXELS], base_pixel_size / PIXEL_SIZE, order=3)
    size = dem0.shape[0] * PIXEL_SIZE
    np.save(out / "base.npy", dem0)

    # a single 20 m crater on a flat patch
    single = np.zeros((120, 120))
    CraterField().place_craters_dem([Crater(30.0, 30.0, 20.0)], single, PIXEL_SIZE)
    np.save(out / f"{version}_single.npy", single)

    # a crater field with the ortho_nominal settings of each version
    crater_field = CraterField()
    if version == "previous":
        np.random.seed(seed)
        crater_field.generate(k=1.0, size_x=size, size_y=size, h_min=2.0, h_max=20.0, x_init=0, y_init=0)
        dem = crater_field.place_craters_dem(crater_field.craters, dem0.copy(), PIXEL_SIZE)
        stamp = lambda z: crater_field.place_craters_dem(crater_field.craters, z, PIXEL_SIZE)  # noqa: E731
    else:
        frame = {"x_min": -size / 2, "y_max": size / 2}
        crater_field.generate(
            size_x=size, size_y=size, surface_age_ga=3.9, terrain="highland", d_min=2.0, d_max=50.0, seed=seed,
            x_init=-size / 2, y_init=-size / 2,
        )  # fmt: skip
        dem = crater_field.place_craters_dem(crater_field.craters, dem0.copy(), PIXEL_SIZE, **frame)
        stamp = lambda z: crater_field.place_craters_dem(crater_field.craters, z, PIXEL_SIZE, **frame)  # noqa: E731
    np.save(out / f"{version}_field.npy", dem)
    runs = [stamp(np.zeros_like(dem0)) for _ in range(4)]
    summary = {
        "n": len(crater_field.craters),
        "diameters": [float(c.diameter) for c in crater_field.craters],
        "repeat_max_difference_m": float(max(np.abs(r - runs[0]).max() for r in runs[1:])),
    }
    json.dump(summary, open(out / f"{version}.json", "w"))

    if version == "current":
        # a mare surface with thin regolith, so larger craters take the other morphologies
        mare = CraterField()
        mare.generate(
            size_x=size, size_y=size, surface_age_ga=3.9, terrain="mare", d_min=2.0, d_max=50.0,
            regolith_thickness=2.0, seed=seed + 4, x_init=-size / 2, y_init=-size / 2,
        )  # fmt: skip
        json.dump(
            {
                "morphology_initial": [c.morphology_initial for c in mare.craters],
                "morphology": [c.morphology for c in mare.craters],
                "diameter_initial": [c.diameter_initial for c in mare.craters],
                "depth_ratio": [c.depth / c.diameter for c in mare.craters],
                "age_myr": [c.age_myr for c in mare.craters],
            },
            open(out / "current_mare.json", "w"),
        )
        gallery = {}
        for name in ("normal", "central_mound", "flat_bottomed", "concentric"):
            for state in (0.0, 10.0, 24.0):
                patch = np.zeros((200, 200))
                crater = Crater(x=50.0, y=50.0, diameter=40.0, morphology_initial=name, degradation_state=state)
                gallery[f"{name}_{state:g}"] = CraterField().place_craters_dem([crater], patch, PIXEL_SIZE)
        np.savez(out / "gallery.npz", **gallery)
    print(f"{version}: {summary['n']} craters")


def plot(output_dir: str, title: str) -> None:
    import matplotlib as mpl

    mpl.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import LightSource

    out = Path(output_dir)
    previous_color, current_color = "#2a78d6", "#eb6834"
    ink, ink_secondary, grid, surface = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"
    plt.rcParams.update(
        {
            "font.size": 9,
            "axes.edgecolor": grid,
            "axes.labelcolor": ink_secondary,
            "xtick.color": ink_secondary,
            "ytick.color": ink_secondary,
            "axes.titlecolor": ink,
            "figure.facecolor": surface,
            "axes.facecolor": surface,
            "axes.titlesize": 10,
            "axes.titleweight": "bold",
        }
    )
    base = np.load(out / "base.npy")
    previous, current = json.load(open(out / "previous.json")), json.load(open(out / "current.json"))
    size = base.shape[0] * PIXEL_SIZE
    extent = (-size / 2, size / 2, -size / 2, size / 2)

    def clean(ax, keep=("left", "bottom")):
        for name, spine in ax.spines.items():
            spine.set_visible(name in keep)

    # the same tile
    fig, axes = plt.subplots(1, 3, figsize=(15, 5.4))
    light = LightSource(azdeg=270, altdeg=12)
    panels = (
        (base, "Base DEM (5 m/px, upsampled to 0.5 m/px)"),
        (np.load(out / "previous_field.npy"), f"Previous: {previous['n']:,} craters (CFA density 1.0, 2-20 m)"),
        (np.load(out / "current_field.npy"), f"Current: {current['n']} visible craters (3.9 Gyr highland, 2-50 m)"),
    )
    for ax, (dem, panel_title) in zip(axes, panels):
        shade = light.hillshade(np.nan_to_num(dem, nan=np.nanmean(dem)), dx=PIXEL_SIZE, dy=PIXEL_SIZE)
        ax.imshow(shade, cmap="gray", extent=extent, vmin=0, vmax=1)
        ax.set_title(panel_title, loc="left")
        ax.set_xlabel("x (m)")
        clean(ax, keep=())
    axes[0].set_ylabel("y (m)")
    fig.suptitle(f"Craters added to the same {size:.0f} x {size:.0f} m tile ({title})", x=0.01, ha="left", fontsize=11)
    fig.tight_layout()
    fig.savefig(out / "compare_tile.png", dpi=80)

    # one fresh 20 m crater
    previous_single, current_single = np.load(out / "previous_single.npy"), np.load(out / "current_single.npy")
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.4), gridspec_kw={"width_ratios": [1.6, 1, 1]})
    ax = axes[0]
    x = (np.arange(previous_single.shape[1]) - 60) * PIXEL_SIZE
    ax.plot(x, previous_single[60], color=previous_color, lw=2, label="previous")
    ax.plot(x, current_single[60], color=current_color, lw=2, label="current")
    for rim in (-10, 10):
        ax.axvline(rim, color=ink_secondary, lw=0.8, ls=(0, (3, 3)))
    ax.text(-9.6, 0.6, "nominal rim", color=ink_secondary, fontsize=8, va="top")
    previous_rim = abs(x[np.argmax(np.nan_to_num(previous_single[60], nan=-np.inf)[x < 0])])
    previous_depth = np.nanmax(previous_single[60]) - np.nanmin(previous_single[60])
    current_depth = current_single[60].max() - current_single[60].min()
    previous_nan = int(np.sum(~np.isfinite(previous_single)))
    ax.text(
        13,
        -0.62,
        f"previous\nrim at ±{previous_rim:.0f} m (D = {2 * previous_rim:.0f} m)\n"
        f"rim-to-floor {previous_depth:.2f} m (d/D {previous_depth / (2 * previous_rim):.3f})"
        + (f"\n{previous_nan} NaN pixel at the center" if previous_nan else ""),
        color=ink,
        fontsize=8,
        va="top",
    )
    ax.text(
        -29.5,
        -1.15,
        f"current\nrim at ±10 m (D = 20 m)\nrim-to-floor {current_depth:.2f} m (d/D {current_depth / 20:.3f})",
        color=ink,
        fontsize=8,
        va="top",
    )
    ax.set_xlim(-30, 30)
    ax.set_ylim(-2.05, 0.65)
    ax.set_xlabel("distance from center (m)")
    ax.set_ylabel("elevation (m)")
    ax.set_title("Profile of one fresh 20 m crater", loc="left")
    ax.grid(True, color=grid, lw=0.6)
    ax.set_axisbelow(True)
    ax.legend(frameon=False, loc="lower right")
    clean(ax)
    light = LightSource(azdeg=270, altdeg=25)
    for ax, dem, name, color in zip(
        axes[1:], (previous_single, current_single), ("previous", "current"), (previous_color, current_color)
    ):
        # the previous code leaves a NaN at the crater center; fill it with the mean of its neighbors
        filled = np.where(np.isfinite(dem), dem, np.nanmean(dem[59:62, 59:62]))
        shade = light.hillshade(filled, dx=PIXEL_SIZE, dy=PIXEL_SIZE, vert_exag=2)
        ax.imshow(shade, cmap="gray", extent=(-30, 30, -30, 30))
        ax.add_patch(plt.Circle((0, 0), 10, fill=False, color=color, lw=1.2, ls=(0, (3, 3))))
        ax.set_title(f"{name} (dashed: nominal 20 m rim)", loc="left")
        ax.set_xlabel("x (m)")
        clean(ax, keep=())
    fig.tight_layout()
    fig.savefig(out / "compare_single.png", dpi=80)

    # morphology gallery
    gallery = np.load(out / "gallery.npz")
    labels = {"normal": "normal", "central_mound": "central mound", "flat_bottomed": "flat-bottomed"}
    labels["concentric"] = "concentric"
    fig, axes = plt.subplots(3, 4, figsize=(12, 9.2))
    light = LightSource(azdeg=270, altdeg=20)
    for j, name in enumerate(labels):
        for i, state in enumerate((0.0, 10.0, 24.0)):
            ax = axes[i, j]
            dem = gallery[f"{name}_{state:g}"]
            ax.imshow(light.hillshade(dem, dx=PIXEL_SIZE, dy=PIXEL_SIZE, vert_exag=1.5), cmap="gray")
            ax.set_xticks([])
            ax.set_yticks([])
            clean(ax, keep=())
            if i == 0:
                ax.set_title(labels[name], loc="left")
            ax.text(
                4,
                194,
                f"K = {state:g} m²   depth {dem.max() - dem.min():.2f} m",
                color="white",
                fontsize=8,
                bbox={"facecolor": "black", "alpha": 0.45, "lw": 0, "pad": 1.5},
            )
    for i, label in enumerate(("fresh", "degraded", "more degraded")):
        axes[i, 0].set_ylabel(label, color=ink_secondary)
    fig.suptitle(
        "Current: the four morphologies of a 40 m crater, fresh and degrading (previous: only a bowl, never degraded)",
        x=0.01,
        ha="left",
        fontsize=11,
    )
    fig.tight_layout()
    fig.savefig(out / "compare_gallery.png", dpi=72)

    # statistics
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.4))
    ax = axes[0]
    area = (size / 1000) ** 2
    for diameters, color, label in (
        (previous["diameters"], previous_color, "previous"),
        (current["diameters"], current_color, "current"),
    ):
        ordered = np.sort(diameters)[::-1]
        ax.loglog(ordered, np.arange(1, len(ordered) + 1) / area, color=color, lw=2, label=label)
    diameters = np.geomspace(2, 50, 50)
    ax.loglog(diameters, 1.54 * (diameters / 1000) ** -2, color=ink_secondary, lw=1, ls=(0, (2, 2)))
    ax.text(14, 1.54 * (14 / 1000) ** -2 * 1.4, "geometric saturation", color=ink_secondary, fontsize=8, rotation=-24)
    ax.set_xlabel("crater diameter (m)")
    ax.set_ylabel("cumulative craters per km²")
    ax.set_title("Size-frequency distribution", loc="left")
    ax.grid(True, color=grid, lw=0.6)
    ax.set_axisbelow(True)
    ax.legend(frameon=False, loc="lower left")
    clean(ax)

    mare = json.load(open(out / "current_mare.json"))
    names = ("normal", "central_mound", "flat_bottomed", "concentric")
    formed = [mare["morphology_initial"].count(name) for name in names]
    kept = [
        sum(1 for a, b in zip(mare["morphology_initial"], mare["morphology"]) if a == name and b == name)
        for name in names
    ]
    ax = axes[1]
    ax.barh(range(4), formed, color=current_color, height=0.6, alpha=0.35)
    ax.barh(range(4), kept, color=current_color, height=0.6)
    ax.set_xscale("log")
    ax.set_xlim(0.8, max(formed) * 3)
    for i, (n_formed, n_kept) in enumerate(zip(formed, kept)):
        text = f"{n_formed}" if i == 0 else f"{n_formed} formed, {n_kept} still {names[i].replace('_', ' ')}"
        ax.text(max(n_formed, 1) * 1.15, i, text, va="center", color=ink, fontsize=8)
    ax.set_yticks(range(4), ["normal", "central mound", "flat-bottomed", "concentric"])
    ax.invert_yaxis()
    ax.set_xlabel("craters (log)")
    ax.set_title("Current, mare + 2 m regolith: morphology", loc="left")
    ax.text(
        0.98,
        0.04,
        'faded: degraded into normal\nprevious: all craters "normal"',
        transform=ax.transAxes,
        ha="right",
        color=ink_secondary,
        fontsize=8,
    )
    ax.grid(True, axis="x", color=grid, lw=0.6)
    ax.set_axisbelow(True)
    clean(ax)

    ax = axes[2]
    points = ax.scatter(
        mare["diameter_initial"],
        mare["depth_ratio"],
        c=np.log10(np.maximum(mare["age_myr"], 1e-3)),
        cmap="Oranges",
        s=26,
        edgecolor=surface,
        linewidth=0.8,
        vmin=-2,
        vmax=1.5,
    )
    for level, label, offset in ((0.04, "visibility limit 0.04", -0.006), (0.113, "fresh 0.113", 0.003)):
        ax.axhline(level, color=ink_secondary, lw=0.8, ls=(0, (3, 3)))
        ax.text(30, level + offset, label, color=ink_secondary, fontsize=8, ha="right")
    ax.set_xscale("log")
    ax.set_ylim(0.025, 0.125)
    ax.set_xlabel("fresh diameter (m)")
    ax.set_ylabel("depth / diameter")
    ax.set_title("Current, mare: depth/diameter vs age", loc="left")
    colorbar = fig.colorbar(points, ax=ax, pad=0.01)
    colorbar.set_label("age (log10 Myr)", color=ink_secondary)
    colorbar.outline.set_visible(False)
    ax.text(0.02, 0.05, "previous: every crater fresh, no age", transform=ax.transAxes, color=ink_secondary, fontsize=8)
    ax.grid(True, color=grid, lw=0.6)
    ax.set_axisbelow(True)
    clean(ax)
    fig.tight_layout()
    fig.savefig(out / "compare_stats.png", dpi=80)

    for version, summary in (("previous", previous), ("current", current)):
        difference = summary["repeat_max_difference_m"]
        print(f"{version}: {summary['n']} craters, repeated stamping differs by {difference:.3g} m")


def main():
    parser = argparse.ArgumentParser(description="Compare crater generation with a previous git revision.")
    parser.add_argument("--previous", required=True, help="Git revision of the previous crater code.")
    parser.add_argument("--base-dem", default=str(DEFAULT_BASE_DEM), help="Base DEM GeoTIFF.")
    parser.add_argument("--output-dir", default="tmp/crater_comparison", help="Folder for the figures.")
    parser.add_argument("--seed", type=int, default=7, help="Seed of the crater fields.")
    parser.add_argument("--generate", choices=("previous", "current"), help=argparse.SUPPRESS)
    parser.add_argument("--data-dir", help=argparse.SUPPRESS)
    args = parser.parse_args()

    if args.generate:  # child process with one version of lunasynth on sys.path
        generate(args.generate, args.base_dem, args.data_dir, args.seed)
        return

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as work:
        work = Path(work)
        previous_src = work / "previous"
        previous_src.mkdir()
        archive = subprocess.run(
            ["git", "-C", str(REPO_ROOT), "archive", args.previous, "src"], check=True, capture_output=True
        )
        subprocess.run(["tar", "-x", "-C", str(previous_src)], input=archive.stdout, check=True)
        data = work / "data"
        data.mkdir()
        for version, src in (("previous", previous_src / "src"), ("current", REPO_ROOT / "src")):
            env = {**os.environ, "PYTHONPATH": str(src), "LUNASYNTH_LOG_DIR": str(work)}
            command = [sys.executable, __file__, "--previous", args.previous, "--generate", version]
            command += ["--base-dem", args.base_dem, "--data-dir", str(data), "--seed", str(args.seed)]
            subprocess.run(command, check=True, env=env, cwd=work)
        plot(str(data), Path(args.base_dem).stem)
        for name in ("compare_tile.png", "compare_single.png", "compare_gallery.png", "compare_stats.png"):
            (output_dir / name).write_bytes((data / name).read_bytes())
    print(f"Saved figures to {output_dir}")


if __name__ == "__main__":
    main()
